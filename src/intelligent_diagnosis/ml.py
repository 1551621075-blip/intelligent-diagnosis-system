"""Real LightGBM training, held-out evaluation, and integrity-checked inference.

All observations are generated by our original electrical simulator. Devices,
not rows, are split before fitting. Hyperparameters and abstention gates use only
validation devices; the test partition is evaluated once after selection. Scores
are multiclass model probabilities, NOT strictly calibrated failure likelihoods.
Artifacts are text/JSON only; activation belongs to the application's database.
"""

import hashlib
import json
import math
import os
import re
import tempfile
from pathlib import Path
from typing import Any

import lightgbm as lgb
import numpy as np
import sklearn
from sklearn.dummy import DummyClassifier
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, classification_report, f1_score, log_loss
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler

from .features import FEATURE_COLUMNS, FEATURE_SCHEMA_VERSION, extract_features
from .schemas import DiagnosisRequest, Domain, DomainError, Prediction
from .synthetic import CLASS_DOMAIN, CLASSES, SYNTHETIC_VERSION, make_request

MODEL_FORMAT_VERSION = 1
VERSION_PATTERN = re.compile(r"sim-lgbm-[0-9a-f]{20}\Z")
EVENTS_PER_CLASS_PER_DEVICE = 2
CANDIDATES = (
    {"num_leaves": 7, "n_estimators": 65, "learning_rate": 0.08, "min_child_samples": 12},
    {"num_leaves": 15, "n_estimators": 100, "learning_rate": 0.06, "min_child_samples": 20},
)
CONFIDENCE_GRID = (0.60, 0.70, 0.80, 0.90, 0.95)
ENTROPY_GRID = (0.20, 0.35, 0.50, 0.75, 1.0)
RANGE_PADDING_GRID = (0.05, 0.15, 0.30)
MAX_VALIDATION_SELECTIVE_ERROR = 0.05


def _canonical(value: Any) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), allow_nan=False).encode("utf-8")


def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _entropy(probabilities: np.ndarray) -> np.ndarray:
    safe = np.clip(probabilities, 1e-15, 1)
    return -(safe * np.log(safe)).sum(axis=1) / math.log(probabilities.shape[1])


def _metrics(y: np.ndarray, probabilities: np.ndarray, classes: tuple[str, ...]) -> dict:
    predicted = probabilities.argmax(axis=1)
    return {
        "n_events": int(len(y)),
        "accuracy": float(accuracy_score(y, predicted)),
        "macro_f1": float(f1_score(y, predicted, labels=np.arange(len(classes)), average="macro")),
        "log_loss": float(log_loss(y, probabilities, labels=np.arange(len(classes)))),
        "class_metrics": classification_report(
            y, predicted, labels=np.arange(len(classes)), target_names=list(classes),
            output_dict=True, zero_division=0,
        ),
    }


def _bounds(matrix: np.ndarray, padding: float) -> tuple[np.ndarray, np.ndarray]:
    low, high = matrix.min(axis=0), matrix.max(axis=0)
    # Constant channels still have finite support, not infinite OOD tolerance.
    width = np.maximum(high - low, np.maximum(np.abs(low), 1.0) * 0.02)
    return low - width * padding, high + width * padding


def _gate(
    matrix: np.ndarray, probabilities: np.ndarray, low: np.ndarray, high: np.ndarray,
    min_confidence: float, max_entropy: float,
) -> np.ndarray:
    return (
        np.isfinite(matrix).all(axis=1)
        & (matrix >= low).all(axis=1)
        & (matrix <= high).all(axis=1)
        & (probabilities.max(axis=1) >= min_confidence)
        & (_entropy(probabilities) <= max_entropy)
    )


def _select_gate(
    train: np.ndarray, validation: np.ndarray, labels: np.ndarray, probabilities: np.ndarray,
) -> tuple[dict, np.ndarray, np.ndarray]:
    """Maximize validation coverage subject to empirical selective-error budget.

    This is a validation heuristic, not a confidence interval, calibration claim,
    or a target for test accuracy. Range probes only test extreme numerical OOD;
    they do not establish detection of every unseen failure mode.
    """
    predicted = probabilities.argmax(axis=1)
    best = None
    trials = []
    minimum_accepted = min(len(labels), max(8, math.ceil(len(labels) * 0.2)))
    for padding in RANGE_PADDING_GRID:
        low, high = _bounds(train, padding)
        for confidence in CONFIDENCE_GRID:
            for entropy in ENTROPY_GRID:
                mask = _gate(validation, probabilities, low, high, confidence, entropy)
                count = int(mask.sum())
                error = float(np.mean(predicted[mask] != labels[mask])) if count else None
                trial = {
                    "range_padding": padding, "min_confidence": confidence,
                    "max_normalized_entropy": entropy, "accepted": count,
                    "coverage": count / len(labels), "selective_error": error,
                }
                trials.append(trial)
                if count < minimum_accepted or error is None:
                    continue
                if error > MAX_VALIDATION_SELECTIVE_ERROR:
                    continue
                rank = (count, -error, confidence, -entropy, -padding)
                if best is None or rank > best[0]:
                    best = (rank, trial, low, high)
    if best is None:
        low, high = _bounds(train, RANGE_PADDING_GRID[0])
        selected = {
            "range_padding": RANGE_PADDING_GRID[0], "min_confidence": 1.000001,
            "max_normalized_entropy": 0.0, "accepted": 0, "coverage": 0.0,
            "selective_error": None,
        }
    else:
        _, selected, low, high = best
    selected = dict(selected)
    selected["validation_error_budget"] = MAX_VALIDATION_SELECTIVE_ERROR
    selected["minimum_validation_accepted"] = minimum_accepted
    selected["selection_partition"] = "validation"
    selected["calibrated_probability"] = False
    selected["selection_trials"] = trials
    # Deterministic, validation-only extreme probes: move one channel outside
    # every candidate's widest training envelope. No test observations involved.
    widest_low, widest_high = _bounds(train, max(RANGE_PADDING_GRID))
    probes = validation.copy()
    for row in range(len(probes)):
        column = row % probes.shape[1]
        probes[row, column] = widest_high[column] + max(
            1.0, widest_high[column] - widest_low[column]
        )
    selected["validation_extreme_range_probe_rejection"] = float(
        np.mean(~((probes >= low).all(axis=1) & (probes <= high).all(axis=1)))
    )
    return selected, low, high


def _selective_metrics(labels: np.ndarray, probabilities: np.ndarray, accepted: np.ndarray) -> dict:
    count = int(accepted.sum())
    return {
        "accepted_events": count,
        "rejected_events": int(len(labels) - count),
        "coverage": count / len(labels),
        "selective_accuracy": (
            float(np.mean(probabilities.argmax(axis=1)[accepted] == labels[accepted]))
            if count else None
        ),
    }


def _dataset(seed: int, n_devices: int) -> tuple[dict, dict]:
    rng = np.random.default_rng(seed)
    device_ids = [f"sim-{seed}-device-{index:05d}" for index in range(n_devices)]
    order = rng.permutation(n_devices)
    train_end, validation_end = int(n_devices * 0.6), int(n_devices * 0.8)
    split_indices = {
        "train": order[:train_end], "validation": order[train_end:validation_end],
        "test": order[validation_end:],
    }
    data: dict = {}
    splits: dict = {}
    for partition, indices in split_indices.items():
        splits[partition] = {
            "n_devices": len(indices), "device_ids": [device_ids[int(index)] for index in indices],
            "n_events": int(len(indices) * sum(map(len, CLASSES.values()))
                            * EVENTS_PER_CLASS_PER_DEVICE),
        }
        data[partition] = {}
        for domain, classes in CLASSES.items():
            rows, labels = [], []
            for device_index in indices:
                for label, class_id in enumerate(classes):
                    for repeat in range(EVENTS_PER_CLASS_PER_DEVICE):
                        event_seed = int(rng.integers(0, 2**31 - 1))
                        request = make_request(
                            class_id, seed=event_seed, device_id=device_ids[int(device_index)],
                            request_id=f"sim-event-{domain.value}-{device_index}-{label}-{repeat}",
                        )
                        features, issues = extract_features(request, domain)
                        if issues:
                            raise DomainError("TRAINING_DATA_INVALID", ";".join(issues), 500)
                        rows.append([features[column] for column in FEATURE_COLUMNS[domain]])
                        labels.append(label)
            data[partition][domain] = (np.asarray(rows, dtype=float), np.asarray(labels, dtype=int))
    return data, splits


def _evaluation_fingerprint(data: dict, splits: dict) -> str:
    """Identify actual frozen evaluation observations, not an accuracy or model hash."""
    payload = {
        "feature_schema_version": FEATURE_SCHEMA_VERSION,
        "synthetic_version": SYNTHETIC_VERSION,
        "partitions": {
            partition: {
                "device_ids": splits[partition]["device_ids"],
                "domains": {
                    domain.value: {
                        "feature_columns": list(FEATURE_COLUMNS[domain]),
                        "classes": list(CLASSES[domain]),
                        "features": data[partition][domain][0].tolist(),
                        "labels": data[partition][domain][1].tolist(),
                    }
                    for domain in Domain
                },
            }
            for partition in ("validation", "test")
        },
    }
    return _digest(_canonical(payload))


def _append_feedback(data: dict, splits: dict, records: list[dict] | None) -> dict:
    """Consume locally exported expert labels in train only, never relabel held-out data.

    The caller authorizes expert feedback export. This function verifies schema,
    event identity, conflicting labels, domain and measurement quality. It never
    treats a record's mere presence as evidence of repair or authorization.
    """
    if records is None:
        records = []
    if not isinstance(records, list):
        raise DomainError("FEEDBACK_INVALID", "反馈训练输入必须为记录列表", 422)
    frozen_devices = {
        device for partition in ("validation", "test") for device in splits[partition]["device_ids"]
    }
    train_devices = set(splits["train"]["device_ids"])
    original_train_devices = set(train_devices)
    seen_events: dict[str, str] = {}
    seen_requests: dict[tuple[str, str], str] = {}
    seen_windows: dict[tuple[str, int], str] = {}
    seen_feedback: dict[str, str] = {}
    accepted, rejected, duplicates = [], [], []
    additions: dict[Domain, list] = {domain: [] for domain in Domain}
    for index, record in enumerate(records):
        if not isinstance(record, dict):
            raise DomainError("FEEDBACK_INVALID", f"反馈记录{index}不是对象", 422)
        required = {"event_id", "device_id", "request", "confirmed_class", "feedback_id"}
        if not required <= set(record):
            raise DomainError("FEEDBACK_INVALID", f"反馈记录{index}缺少必要字段", 422)
        if any(not isinstance(record[key], str) or not record[key].strip()
               for key in required - {"request"}):
            raise DomainError("FEEDBACK_INVALID", f"反馈记录{index}的标识或类别无效", 422)
        try:
            request = DiagnosisRequest.model_validate(record["request"])
        except (ValueError, TypeError) as exc:
            raise DomainError("FEEDBACK_INVALID", f"反馈原始请求无效: {exc}", 422) from exc
        label = record["confirmed_class"]
        if label not in CLASS_DOMAIN or record["device_id"] != request.device_id:
            raise DomainError("FEEDBACK_INVALID", "反馈类别未知或设备标识与原请求不一致", 422)
        domain = CLASS_DOMAIN[label]
        if request.domain is not None and request.domain != domain:
            raise DomainError("FEEDBACK_DOMAIN_MISMATCH", "专家标签与原请求故障域不一致", 422)
        content_hash = _digest(_canonical({
            "device_id": request.device_id, "request": request.model_dump(mode="json"),
            "confirmed_class": label,
        }))
        event_key = record["event_id"]
        request_key = (request.device_id, request.request_id)
        window_key = (request.device_id, request.fault_time_ms)
        feedback_key = record["feedback_id"]
        if ((event_key in seen_events and seen_events[event_key] != content_hash)
                or (request_key in seen_requests and seen_requests[request_key] != content_hash)
                or (window_key in seen_windows and seen_windows[window_key] != label)
                or (feedback_key in seen_feedback and seen_feedback[feedback_key] != content_hash)):
            raise DomainError("FEEDBACK_CONFLICT", "同一事件、窗口或反馈ID存在冲突标注", 409)
        duplicate = event_key in seen_events or request_key in seen_requests or window_key in seen_windows
        seen_events[event_key] = content_hash
        seen_requests[request_key] = content_hash
        seen_windows[window_key] = label
        seen_feedback[feedback_key] = content_hash
        provenance = {"event_id": event_key, "feedback_id": feedback_key,
                      "device_id": request.device_id, "confirmed_class": label,
                      "content_sha256": content_hash}
        if duplicate:
            duplicates.append(provenance)
            continue
        if request.device_id in frozen_devices:
            rejected.append({**provenance, "reason": "held_out_device"})
            continue
        features, issues = extract_features(request, domain)
        if issues:
            rejected.append({**provenance, "reason": "invalid_window", "issues": issues})
            continue
        additions[domain].append((
            [features[column] for column in FEATURE_COLUMNS[domain]], CLASSES[domain].index(label)
        ))
        accepted.append(provenance)
        train_devices.add(request.device_id)
    for domain, rows in additions.items():
        if rows:
            x, y = data["train"][domain]
            extra_x, extra_y = zip(*rows, strict=True)
            data["train"][domain] = (
                np.concatenate([x, np.asarray(extra_x, dtype=float)]),
                np.concatenate([y, np.asarray(extra_y, dtype=int)]),
            )
    splits["train"]["device_ids"] += sorted(train_devices - original_train_devices)
    splits["train"]["n_devices"] = len(train_devices)
    splits["train"]["n_events"] += len(accepted)
    return {
        "source": "caller-authorized local expert feedback export",
        "partition": "train_only", "received_records": len(records),
        "accepted_count": len(accepted), "rejected_count": len(rejected),
        "duplicate_count": len(duplicates), "accepted": accepted,
        "rejected": rejected, "duplicates": duplicates,
        "accepted_content_sha256": _digest(_canonical(sorted(
            row["content_sha256"] for row in accepted
        ))),
        "held_out_devices_unchanged": True,
    }


def train_models(
    model_dir: Path, seed: int = 17, n_devices: int = 240,
    feedback_records: list[dict] | None = None,
) -> dict:
    """Train both domains and persist model_dir/<content-version>/ atomically.

    At least 24 simulated devices are needed to form three useful partitions.
    Each contributes two distinct events per class; all events/windows of each
    device remain together. Repeating identical training reuses identical files,
    but existing differing content is never overwritten. No database is changed.
    """
    if not isinstance(n_devices, int) or isinstance(n_devices, bool) or n_devices < 24:
        raise ValueError("n_devices must be an integer >= 24")
    if not isinstance(seed, int) or isinstance(seed, bool) or seed < 0:
        raise ValueError("seed must be a nonnegative integer")
    data, splits = _dataset(seed, n_devices)
    evaluation_fingerprint = _evaluation_fingerprint(data, splits)
    feedback_summary = _append_feedback(data, splits, feedback_records)
    config = {
        "seed": seed, "n_devices": n_devices,
        "events_per_class_per_device": EVENTS_PER_CLASS_PER_DEVICE,
        "grouping": "device_id; all event windows stay with their device",
        "split_fractions": [0.6, 0.2, 0.2], "synthetic_version": SYNTHETIC_VERSION,
        "feature_schema_version": FEATURE_SCHEMA_VERSION,
        "candidates": list(CANDIDATES), "lightgbm_version": lgb.__version__,
        "numpy_version": np.__version__, "sklearn_version": sklearn.__version__,
        "source": "original synthetic electrical simulation; no production data",
    }
    metadata: dict = {
        "format_version": MODEL_FORMAT_VERSION,
        "config": config, "splits": splits, "domains": {}, "metrics": {},
        "baseline": {}, "threshold": {},
        "evaluation_fingerprint": evaluation_fingerprint,
        "feedback": feedback_summary,
        "limitations": [
            "Synthetic held-out metrics do not estimate production accuracy.",
            "Softmax scores and validation abstention gates are not strictly calibrated probabilities.",
            "Marginal-range OOD cannot detect every novel or physically inconsistent event.",
            "Test devices are not used for hyperparameter or reliability-threshold selection.",
        ],
    }
    model_texts: dict[str, bytes] = {}
    for domain, classes in CLASSES.items():
        train_x, train_y = data["train"][domain]
        validation_x, validation_y = data["validation"][domain]
        results, candidates = [], []
        for parameters in CANDIDATES:
            estimator = lgb.LGBMClassifier(
                objective="multiclass", num_class=len(classes), random_state=seed,
                n_jobs=1, deterministic=True, force_col_wise=True, verbosity=-1,
                **parameters,
            )
            estimator.fit(train_x, train_y, feature_name=list(FEATURE_COLUMNS[domain]))
            probabilities = estimator.booster_.predict(validation_x, num_threads=1)
            validation_metrics = _metrics(validation_y, probabilities, classes)
            results.append({"parameters": parameters, "validation": validation_metrics})
            candidates.append((estimator, probabilities))
        selected_index = min(
            range(len(results)),
            key=lambda index: (-results[index]["validation"]["macro_f1"],
                               results[index]["validation"]["log_loss"], index),
        )
        estimator, validation_probabilities = candidates[selected_index]
        gate, low, high = _select_gate(train_x, validation_x, validation_y, validation_probabilities)
        # Everything above this line is frozen before evaluating the test set.
        test_x, test_y = data["test"][domain]
        test_probabilities = estimator.booster_.predict(test_x, num_threads=1)
        accepted = _gate(test_x, test_probabilities, low, high,
                         gate["min_confidence"], gate["max_normalized_entropy"])
        domain_metrics = {
            "validation": results[selected_index]["validation"],
            "test": _metrics(test_y, test_probabilities, classes),
            "test_selective": _selective_metrics(test_y, test_probabilities, accepted),
        }
        baselines = {}
        for name, baseline in (
            ("majority_prior", DummyClassifier(strategy="prior")),
            ("linear_logistic", make_pipeline(
                StandardScaler(), LogisticRegression(C=1.0, max_iter=800, random_state=seed)
            )),
        ):
            baseline.fit(train_x, train_y)
            baselines[name] = _metrics(test_y, baseline.predict_proba(test_x), classes)
        filename = f"{domain.value}.txt"
        text = estimator.booster_.model_to_string().encode("utf-8")
        model_texts[filename] = text
        metadata["domains"][domain.value] = {
            "classes": list(classes), "feature_columns": list(FEATURE_COLUMNS[domain]),
            "model_file": filename, "model_sha256": _digest(text),
            "selected_candidate": selected_index, "candidate_validation": results,
            "range_low": low.tolist(), "range_high": high.tolist(),
            "test_macro_f1": domain_metrics["test"]["macro_f1"],
            "test_accuracy": domain_metrics["test"]["accuracy"],
            "train_events": int(len(train_y)),
            "feedback_train_events": sum(
                CLASS_DOMAIN[row["confirmed_class"]] == domain
                for row in feedback_summary["accepted"]
            ),
        }
        metadata["metrics"][domain.value] = domain_metrics
        metadata["baseline"][domain.value] = baselines
        metadata["threshold"][domain.value] = gate
    metadata_hash = _digest(_canonical(metadata))
    version = f"sim-lgbm-{metadata_hash[:20]}"
    metadata["version"] = version
    metadata["metadata_sha256"] = metadata_hash
    files = {**model_texts, "metadata.json": _canonical(metadata)}
    model_dir = Path(model_dir)
    model_dir.mkdir(parents=True, exist_ok=True)
    destination = model_dir / version

    def check_existing() -> None:
        if not destination.is_dir() or destination.is_symlink():
            raise DomainError("MODEL_VERSION_CONFLICT", "版本路径已存在且不是模型目录", 409)
        if set(path.name for path in destination.iterdir()) != set(files):
            raise DomainError("MODEL_VERSION_CONFLICT", "版本目录已有不同文件，不允许覆盖", 409)
        for filename, content in files.items():
            path = destination / filename
            if path.is_symlink() or not path.is_file() or path.read_bytes() != content:
                raise DomainError("MODEL_VERSION_CONFLICT", "版本目录已有不同内容，不允许覆盖", 409)

    if destination.exists() or destination.is_symlink():
        check_existing()
        return metadata
    with tempfile.TemporaryDirectory(prefix=".training-", dir=model_dir) as staging:
        for filename, content in files.items():
            (Path(staging) / filename).write_bytes(content)
        try:
            os.rename(staging, destination)
        except OSError:
            if destination.exists():
                check_existing()
            else:
                raise
    return metadata


class DiagnosisModels:
    """One immutable, validated two-domain bundle; never silently use another version."""

    def __init__(self, model_dir: Path, version: str):
        if not VERSION_PATTERN.fullmatch(version):
            raise DomainError("MODEL_NOT_FOUND", "模型版本格式无效或不存在", 404)
        directory = Path(model_dir) / version
        if not directory.is_dir() or directory.is_symlink():
            raise DomainError("MODEL_NOT_FOUND", "模型版本不存在", 404)
        self.version = version
        self._models: dict[Domain, lgb.Booster] = {}
        try:
            metadata_path = directory / "metadata.json"
            if metadata_path.is_symlink():
                raise ValueError("symlink metadata is not permitted")
            metadata = json.loads(metadata_path.read_bytes())
            if not isinstance(metadata, dict):
                raise ValueError("metadata must be a JSON object")
            payload = {key: value for key, value in metadata.items()
                       if key not in {"version", "metadata_sha256"}}
            actual_hash = _digest(_canonical(payload))
            if (
                metadata["version"] != version
                or metadata["metadata_sha256"] != actual_hash
                or version != f"sim-lgbm-{actual_hash[:20]}"
                or metadata["format_version"] != MODEL_FORMAT_VERSION
                or metadata["config"]["feature_schema_version"] != FEATURE_SCHEMA_VERSION
                or set(metadata["domains"]) != {domain.value for domain in Domain}
            ):
                raise ValueError("metadata hash/version/schema mismatch")
            for domain, classes in CLASSES.items():
                info = metadata["domains"][domain.value]
                if (info["classes"] != list(classes)
                        or info["feature_columns"] != list(FEATURE_COLUMNS[domain])
                        or info["model_file"] != f"{domain.value}.txt"):
                    raise ValueError("model domain/feature/class schema mismatch")
                path = directory / info["model_file"]
                if path.is_symlink():
                    raise ValueError("symlink model is not permitted")
                content = path.read_bytes()
                if _digest(content) != info["model_sha256"]:
                    raise ValueError("model content hash mismatch")
                booster = lgb.Booster(model_str=content.decode("utf-8"))
                if (booster.feature_name() != list(FEATURE_COLUMNS[domain])
                        or booster.num_model_per_iteration() != len(classes)
                        or booster.dump_model().get("objective", "").split()[0] != "multiclass"):
                    raise ValueError("LightGBM feature/objective/class schema mismatch")
                low, high = np.asarray(info["range_low"]), np.asarray(info["range_high"])
                if (low.shape != (len(FEATURE_COLUMNS[domain]),) or high.shape != low.shape
                        or not np.isfinite(low).all() or not np.isfinite(high).all()
                        or not (low <= high).all()):
                    raise ValueError("invalid OOD support bounds")
                threshold = metadata["threshold"][domain.value]
                if (not 0 <= threshold["min_confidence"] <= 1.000001
                        or not 0 <= threshold["max_normalized_entropy"] <= 1):
                    raise ValueError("invalid reliability threshold")
                self._models[domain] = booster
            self.metadata = metadata
        except (OSError, ValueError, KeyError, TypeError, IndexError, lgb.basic.LightGBMError) as exc:
            raise DomainError("MODEL_INVALID", f"模型完整性或schema校验失败: {exc}", 503) from exc

    def predict(self, domain: Domain, features: dict) -> Prediction:
        try:
            domain = Domain(domain)
        except ValueError as exc:
            raise DomainError("MODEL_DOMAIN_MISMATCH", "不支持的模型故障域", 400) from exc
        columns = FEATURE_COLUMNS[domain]
        if set(features) != set(columns):
            raise DomainError("FEATURE_SCHEMA_MISMATCH", "特征列缺失、多余或混入其他故障域", 400)
        try:
            matrix = np.asarray([[float(features[column]) for column in columns]], dtype=float)
        except (TypeError, ValueError, OverflowError) as exc:
            raise DomainError("FEATURE_SCHEMA_MISMATCH", "特征值必须是数值或NaN", 400) from exc
        if np.isinf(matrix).any():
            raise DomainError("FEATURE_NONFINITE", "特征不能为无穷值", 400)
        probabilities = np.asarray(self._models[domain].predict(matrix, num_threads=1), dtype=float)
        classes = CLASSES[domain]
        if (probabilities.shape != (1, len(classes)) or not np.isfinite(probabilities).all()
                or (probabilities < 0).any() or (probabilities > 1).any()
                or not np.isclose(probabilities.sum(), 1, atol=1e-7)):
            raise DomainError("MODEL_INVALID", "模型未返回有效的多类概率", 503)
        info = self.metadata["domains"][domain.value]
        threshold = self.metadata["threshold"][domain.value]
        low, high = np.asarray(info["range_low"]), np.asarray(info["range_high"])
        reasons = []
        if np.isnan(matrix).any():
            reasons.append("missing_features")
        elif not ((matrix >= low).all() and (matrix <= high).all()):
            reasons.append("out_of_distribution_range")
        if float(probabilities.max()) < threshold["min_confidence"]:
            reasons.append("below_validation_confidence_threshold")
        if float(_entropy(probabilities)[0]) > threshold["max_normalized_entropy"]:
            reasons.append("above_validation_entropy_threshold")
        return Prediction(
            domain=domain, class_id=classes[int(probabilities[0].argmax())],
            scores={class_id: float(score)
                    for class_id, score in zip(classes, probabilities[0], strict=True)},
            model_version=self.version, accepted=not reasons,
            reliability_reason=";".join(reasons) if reasons else "validation_gate_passed_uncalibrated",
        )
